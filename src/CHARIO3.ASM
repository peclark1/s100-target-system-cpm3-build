	ANI	SER$TX$READY
	JZ	COST$NO
	JMP	COST$YES

MIO$COST:
	IN	MIO$STATUS
	ANI	MIO$TX$READY
	JZ	COST$NO
COST$YES:
	MVI	A,0FFH
	RET
COST$NO:
	XRA	A
	RET

;--------------------------------- OUTPUT -----------------------------------
; On entry C contains the output character and B contains the device number.
CO0:
	LDA	CONSOLE$SEL
	CPI	CONSOLE$SERIAL
	JZ	SERIAL$CO
	CPI	CONSOLE$MIO
	JZ	MIO$CO

CIO$CO:
	IN	CIO$STATUS
	ANI	CIO$TX$READY
	JZ	CIO$CO
	MOV	A,C
	OUT	CIO$DATA
	RET

SERIAL$CO:
	IN	SER$A$CTRL
	ANI	SER$TX$READY
	JZ	SERIAL$CO
	MOV	A,C
	OUT	SER$A$DATA
	RET

MIO$CO:
	IN	MIO$STATUS
	ANI	MIO$TX$READY
	JZ	MIO$CO
	MOV	A,C
	OUT	MIO$DATA
	RET

;=============================================================================
; BOOT-TIME CONSOLE ANNOUNCEMENT
;=============================================================================

; Probe each possible output for a bounded interval.  A missing board can
; return either FFH (floating bus, treated as ready) or a value with the ready
; bit clear.  Either case is safe: writes to a missing I/O port are harmless,
; while a never-ready device is omitted after 256 polls.
BCAST$PROBE:
	XRA	A
	STA	BCAST$MASK

	MVI	B,0
BP$CIO:
	IN	CIO$STATUS
	ANI	CIO$TX$READY
	JNZ	BP$CIOY
	DCR	B
	JNZ	BP$CIO
	JMP	BP$SER
BP$CIOY:
	LDA	BCAST$MASK
	ORI	BCAST$CIO
	STA	BCAST$MASK

BP$SER:
	MVI	B,0
BP$SERL:
	IN	SER$A$CTRL
	ANI	SER$TX$READY
	JNZ	BP$SERY
	DCR	B
	JNZ	BP$SERL
	JMP	BP$MIO
BP$SERY:
	LDA	BCAST$MASK
	ORI	BCAST$SERIAL
	STA	BCAST$MASK

BP$MIO:
	MVI	B,0
BP$MIOL:
	IN	MIO$STATUS
	ANI	MIO$TX$READY
	JNZ	BP$MIOY
	DCR	B
	JNZ	BP$MIOL
	RET
BP$MIOY:
	LDA	BCAST$MASK
	ORI	BCAST$MIO
	STA	BCAST$MASK
	RET

BCAST$ANNOUNCE:
	LXI	H,MSG$CONSOLE$PREFIX
	CALL	BCAST$STRING
	LDA	CONSOLE$SEL
	CPI	CONSOLE$SERIAL
	JZ	BA$SER
	CPI	CONSOLE$MIO
	JZ	BA$MIO
	LXI	H,MSG$CONSOLE$CIO
	JMP	BA$PRINT
BA$SER:
	LXI	H,MSG$CONSOLE$SERIAL
	JMP	BA$PRINT
BA$MIO:
	LXI	H,MSG$CONSOLE$MIO
BA$PRINT:
	CALL	BCAST$STRING
	LXI	H,MSG$CONSOLE$EOL
	CALL	BCAST$STRING
	RET

; Zero-terminated string at HL.
BCAST$STRING:
	MOV	A,M
	ORA	A
	RZ
	INX	H
	CALL	BCAST$CHAR
	JMP	BCAST$STRING

; Broadcast character A to every device which passed the startup probe.
; Each individual write is bounded as well, so a device which becomes unready
; after the initial probe still cannot stall CP/M startup.
BCAST$CHAR:
	MOV	C,A
	LDA	BCAST$MASK
	ANI	BCAST$CIO
	JZ	BC$SER
	CALL	BCIO$CHAR
BC$SER:
	LDA	BCAST$MASK
	ANI	BCAST$SERIAL
	JZ	BC$MIO
	CALL	BSER$CHAR
BC$MIO:
	LDA	BCAST$MASK
	ANI	BCAST$MIO
	RZ
	CALL	BMIO$CHAR
	RET

BCIO$CHAR:
	MVI	B,0
BCIO$WAIT:
	IN	CIO$STATUS
	ANI	CIO$TX$READY
	JNZ	BCIO$GO
	DCR	B
	JNZ	BCIO$WAIT
	RET
BCIO$GO:
	MOV	A,C
	OUT	CIO$DATA
	RET

BSER$CHAR:
	MVI	B,0
BSER$WAIT:
	IN	SER$A$CTRL
	ANI	SER$TX$READY
	JNZ	BSER$GO
	DCR	B
	JNZ	BSER$WAIT
	RET
BSER$GO:
	MOV	A,C
	OUT	SER$A$DATA
	RET

BMIO$CHAR:
	MVI	B,0
BMIO$WAIT:
	IN	MIO$STATUS
	ANI	MIO$TX$READY
	JNZ	BMIO$GO
	DCR	B
	JNZ	BMIO$WAIT
	RET
BMIO$GO:
	MOV	A,C
	OUT	MIO$DATA
	RET

MSG$CONSOLE$PREFIX:
	DB	CR,LF,'Console device selected: ',0
MSG$CONSOLE$CIO:
	DB	'Console IO',0
MSG$CONSOLE$SERIAL:
	DB	'Serial IO A',0
MSG$CONSOLE$MIO:
	DB	'SIO',0
MSG$CONSOLE$EOL:
	DB	CR,LF,0

; S100Computers Serial I/O V3 channel A / Z85C30 initialization.
; Same setup as the target 4K master ROM: 4.9152 MHz clock, 38,400 baud, 8N1.
