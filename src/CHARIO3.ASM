;=============================================================================
; DEVICE 0 - IMSAI TARGET CONSOLE ABSTRACTION
;=============================================================================

; Latch the front-panel selection once during CP/M character-device init,
; just as the monitor latches SW09/SW08 during reset.
;
; As a boot-time failsafe, initialize Serial I/O A and then broadcast the
; selected-device message to every output device which becomes ready within a
; bounded probe.  The announcement therefore cannot hang boot if a console
; card is absent or unready, and a user watching the wrong console can still
; see which device CP/M selected.  Normal CP/M I/O after this point goes only
; to the selected console.
CINIT0:
	PUSH	B
	PUSH	D
	PUSH	H

	IN	PANEL$PORT
	ANI	03H
	CPI	03H
	JNZ	CINIT0$SEL
	XRA	A			; reserved 11 -> Console I/O
CINIT0$SEL:
	STA	CONSOLE$SEL

	; Serial A is one of the three announcement targets, so initialize it even
	; when another console is selected. Writes to an absent S-100 I/O address
	; are harmless, and all subsequent Serial A output remains bounded here.
	CALL	SERIAL$INIT$A
	CALL	BCAST$PROBE
	CALL	BCAST$ANNOUNCE

	POP	H
	POP	D
	POP	B
	RET

;------------------------------ INPUT STATUS -------------------------------
; CP/M expects FFH when a character is ready, 00H otherwise.
CIST0:
	LDA	CONSOLE$SEL
	CPI	CONSOLE$SERIAL
	JZ	SERIAL$CIST
	CPI	CONSOLE$MIO
	JZ	MIO$CIST

CIO$CIST:
	IN	CIO$STATUS
	ANI	CIO$RX$READY
	JZ	CIST$NO
	JMP	CIST$YES

SERIAL$CIST:
	IN	SER$A$CTRL
	ANI	SER$RX$READY
	JZ	CIST$NO
	JMP	CIST$YES

MIO$CIST:
	IN	MIO$STATUS
	ANI	MIO$RX$READY
	JZ	CIST$NO
CIST$YES:
	MVI	A,0FFH
	RET
CIST$NO:
	XRA	A
	RET

;---------------------------------- INPUT -----------------------------------
CI0:
	LDA	CONSOLE$SEL
	CPI	CONSOLE$SERIAL
	JZ	SERIAL$CI
	CPI	CONSOLE$MIO
	JZ	MIO$CI

CIO$CI:
	IN	CIO$STATUS
	ANI	CIO$RX$READY
	JZ	CIO$CI
	IN	CIO$DATA
	ANI	7FH
	RET

SERIAL$CI:
	IN	SER$A$CTRL
	ANI	SER$RX$READY
	JZ	SERIAL$CI
	IN	SER$A$DATA
	ANI	7FH
	RET

MIO$CI:
	IN	MIO$STATUS
	ANI	MIO$RX$READY
	JZ	MIO$CI
	IN	MIO$DATA
	ANI	7FH
	RET

;----------------------------- OUTPUT STATUS --------------------------------
; CP/M expects FFH when the device can accept a character, 00H otherwise.
COST0:
	LDA	CONSOLE$SEL
	CPI	CONSOLE$SERIAL
	JZ	SERIAL$COST
	CPI	CONSOLE$MIO
	JZ	MIO$COST

CIO$COST:
	IN	CIO$STATUS
	ANI	CIO$TX$READY
	JZ	COST$NO
	JMP	COST$YES

SERIAL$COST:
