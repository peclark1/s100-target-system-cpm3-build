	OUT	SER$A$CTRL
	MVI	A,0DH
	OUT	SER$A$CTRL
	XRA	A
	OUT	SER$A$CTRL
	MVI	A,0EH
	OUT	SER$A$CTRL
	MVI	A,01H
	OUT	SER$A$CTRL
	RET

